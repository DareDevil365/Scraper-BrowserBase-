    tf_src = tx_src.text_frame
    tf_src.word_wrap = True

    sources = research_data.get("sources", [])
    if sources:
        p = tf_src.paragraphs[0]
        p.text = "The following authoritative sources were compiled:"
        p.font.bold = True
        p.font.size = PtSize(16)
        
        for idx, src in enumerate(sources[:6]):
            p_s = tf_src.add_paragraph()
            title = src.get("title") or src.get("url") or "Link"
            tier = src.get("tier_label") or src.get("label", "Tier 6")
            p_s.text = f"[{idx+1}] {title} ({tier})"
            p_s.font.size = PtSize(13)
            p_s.space_before = PtSize(5)
    else:
        tf_src.paragraphs[0].text = "No sources recorded."

    output_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "outputs")
    os.makedirs(output_dir, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    file_path = os.path.join(output_dir, f"scout_report_{timestamp}.pptx")
    prs.save(file_path)
    return file_path


