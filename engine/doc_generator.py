def pre_filter_and_map_back(research_data: dict) -> dict:
    """Pre-filter research_data using presentation_filter, then map it back so that generate_word/pdf continue to function."""
    from presentation_filter import build_presentable
    
    # Check if already filtered (e.g., if it has gaps / executive_summary)
    if "executive_summary" in research_data and "gaps" in research_data:
        presentable = research_data
    else:
        presentable = build_presentable(research_data)
        
    # Map back to old schema format:
    mapped = {}
    mapped["summary"] = presentable.get("executive_summary") or ""
    mapped["key_takeaways"] = presentable.get("key_takeaways") or []
    
    # Rebuild sections
    sections = []
    for sec in presentable.get("sections", []):
        vid = sec.get("vector_id")
        
        # Find corresponding table rows for this section
        tbl_rows = []
        for t in presentable.get("tables", []):
            if t.get("vector_id") == vid:
                tbl_rows = t.get("rows", [])
                break
                
        sections.append({
            "title": sec.get("title", ""),
            "content": sec.get("body", ""),
            "key_findings": [],
            "data": tbl_rows
        })
    mapped["sections"] = sections
    
    # Map sources
    sources = []
    for src in presentable.get("sources", []):
        sources.append({
            "title": src.get("title"),
            "url": src.get("url"),
            "tier_label": src.get("tier"),
            "label": src.get("tier"),
            "quality_score": 90,  # placeholder/default
            "score": 90,
            "domain": src.get("domain"),
            "tier": src.get("tier"),
            "status": src.get("status")
        })
    mapped["sources"] = sources
    
    # Preserve gaps and tables for generate_excel
    mapped["gaps"] = presentable.get("gaps", [])
    mapped["tables"] = presentable.get("tables", [])
    
    return mapped


